/**
 * チャット送信の入力上限に関する共有定義
 *
 * 設計判断: これらの上限はサーバー（`src/app/api/chat/route.ts` の検証側）と
 * クライアント（`src/app/page.tsx` / `src/components/ChatInput.tsx` の送信側）の
 * **両方**が同じ値を知っていて初めて意味を持つ。以前は上限がサーバー側にしか
 * 無かったため、クライアントは上限を超える会話履歴・本文をそのまま送り、
 * 必ず 400 になるリクエストを往復させてからエラーを表示していた。
 * とくに会話履歴の件数上限は、履歴が増える一方で減らないため
 * **一度超えると以降どの送信も 400 になり、チャットが再読み込みするまで使えなくなる**。
 * 唯一の参照元をここに置き、両側が必ず同じ値を使うようにする
 * （`src/lib/sse.ts` と同じ「送信側と受信側で共有する契約」の置き方。
 * §6 定数・ラベルの一元管理／マジックナンバーを避ける）。
 */
import type { Message } from "./types";

/** 1 リクエストで受け付ける会話履歴の最大メッセージ数（無制限の履歴送信による
 * トークン浪費・リソース枯渇を防ぐ。サーバーはこれを超える配列を 400 で弾き、
 * クライアントは送信前にこの件数まで古い発言を切り落とす）。 */
export const MAX_MESSAGE_COUNT = 50;

/** 1 メッセージ本文の最大文字数（巨大ボディをそのまま Claude へ転送して
 * 課金・メモリを浪費させられないようにする入力上限）。 */
export const MAX_CONTENT_LENGTH = 4000;

/** リクエストボディの最大バイト数。
 *
 * <p>上の 2 つの上限と**独立に決めてはいけない**。件数 × 文字数がこの値を超える
 * 設定にすると、上限内の履歴を送っても 413 になり、しかも弾かれたメッセージは
 * 履歴に残り続けて窓からも抜けない（400 について本モジュールが塞いだのと
 * まったく同じ「復帰できない」状態が、413 で再発する）。
 *
 * <p>見積もりは「日本語 1 文字 = UTF-8 で 3 バイト」ではなく、**JSON 化したときの
 * 最悪ケース（1 符号単位あたり 6 バイト）**で行う。`JSON.stringify` は短縮
 * エスケープを持たない制御文字を 6 バイトのエスケープ表記へ展開するため、
 * 3 バイト換算のままだと「上限内の履歴なのに 413」を見逃す。
 * 関係が崩れていないことは `tests/chat-limits.test.ts` が固定する
 * （係数が本当に最悪ケースかも、実際に JSON 化して確かめている）。 */
export const MAX_BODY_BYTES = 1_500_000;

/** 本文が上限を超えたときにユーザーへ見せる文言（§6 UI 文言は一元管理）。
 * サーバーの検証（`route.ts`）と、送信前に弾く入力欄（`ChatInput.tsx`）の両方が
 * これを使う。片方に書き写すと、上限値を変えたときに文言だけが古い値のまま残る。 */
export const CONTENT_TOO_LONG_MESSAGE = `メッセージ本文が上限（${MAX_CONTENT_LENGTH} 文字）を超えています。`;

/** 本文が空（空白だけを含む）のときにユーザーへ見せる文言（§6 UI 文言は一元管理）。
 * サーバーの検証（`route.ts` の `ERROR_MESSAGES.messageContentEmpty`）と、
 * 送信前に弾く画面側（`page.tsx`）の両方がこれを使う。 */
export const CONTENT_EMPTY_MESSAGE = "メッセージ本文を入力してください。";

/** 会話履歴の件数が上限を超えたときにユーザーへ見せる文言（§6 UI 文言は一元管理）。
 * 上限値を本文へ埋め込む文言は、定数のすぐ隣に置かないと値だけ変えて文言が
 * 古いまま残る。{@link CONTENT_TOO_LONG_MESSAGE} と同じ理由でここに置く。 */
export const TOO_MANY_MESSAGES_MESSAGE = `メッセージ数が上限（${MAX_MESSAGE_COUNT} 件）を超えています。`;

/** 上限を超えた過去の発言を切り詰めたときに末尾へ付ける印。
 * 印なしで切ると、AI から見て「そこで終わった発言」と区別が付かず、
 * 続きを尋ねたときに省略された部分を踏まえない答えが返る。
 * user / assistant のどちらの発言にも付くので文言は「発言」で中立にしてある。
 * 切り口の位置を導くのにこの長さが要るため export する（テストからも参照する）。 */
export const OMITTED_MESSAGE_SUFFIX = "\n\n（以前の発言はここで省略されました）";

/** 最後まで届かなかった回答の末尾に画面側が付ける印（§6 UI 文言は一元管理）。
 *
 * <p>文言は「中断」ではなく「途切れている」にしてある。回答が完結しない理由は
 * 通信の中断だけでなく、**長さの上限（`max_tokens`）に達した**場合も含む。
 * 既定の上限は 1024 トークン（日本語で 500〜700 文字程度）なので後者は日常的に
 * 起こり、それを「中断されました」と表示すると、正常に上限まで生成された回答が
 * 通信障害のように見える。この文字列は次の質問の文脈としてもそのまま送られるため、
 * AI 側が「起きていない中断」を謝る材料にもなってしまう。
 *
 * <p>`page.tsx` が表示・保存する文言だが、定義はここに置く。理由は 2 つある。
 * (1) この印は**末尾にある**ことを前提に {@link OMITTED_MESSAGE_SUFFIX} 側の
 * 切り詰め位置を決めており、片方だけ変えるとその設計根拠が黙って崩れる。
 * (2) 同じ「送信する本文の作り方」に関わる約束事なので、`src/lib/sse.ts` と同じく
 * 送信側と表示側の唯一の参照元を 1 か所に置く。 */
export const TRUNCATED_ANSWER_SUFFIX = "\n\n（この回答はここで途切れています）";

/**
 * 送信しようとしている本文に問題があれば、その理由を返す。
 *
 * <p>送ってよい本文かの規則（空でないこと・上限以内であること）をここに 1 つだけ置き、
 * **表示する側（入力欄）と送る側（画面）の
 * 両方がこれを呼ぶ**。判定を書き写すと、片方だけ直したときに「入力欄は通すのに
 * サーバーが弾く」ずれが生まれる。両者は役割が違うので、どちらも必要:
 * 入力欄は「入力を消さずに理由を見せる」ための表示、送る側は「上限を超えた本文を
 * 履歴に積ませない」ための防御（積むとサーバーが 400 を返す一方で履歴には残り、
 * 往復が成立しないので窓からも抜けず、再読み込みするまで復帰できなくなる）。
 *
 * @param content - 送信しようとしている本文
 * @returns 問題があれば表示する理由、問題なければ null
 */
export function findContentProblem(content: string): string | null {
  // 空白だけの本文はそもそも送れない（サーバーも同じ理由で 400 を返す）。
  // 判定を長さ側だけにしておくと、空白だけの発言が履歴に積まれたときに
  // trimHistoryForRequest がそれを取り除き、窓に user 発言が残らない場合の
  // 予備経路として「1 つ前の質問」を送ってしまう。ユーザーから見ると
  // 空の送信に対して前の質問への回答が返る（何が起きたか分からない）ので、
  // 送る前にここで止める
  if (content.trim() === "") {
    return CONTENT_EMPTY_MESSAGE;
  }
  // 上限を超えていれば、その理由を返す
  if (content.length > MAX_CONTENT_LENGTH) {
    return CONTENT_TOO_LONG_MESSAGE;
  }
  // 問題が無ければ null を返す
  return null;
}

/**
 * 送信する会話履歴を上限件数まで切り詰める。
 *
 * <p>単純に直近 {@link MAX_MESSAGE_COUNT} 件を切り出すだけでは足りない。
 * 履歴は user / assistant が交互に並ぶため、切り出した窓の先頭が assistant 発言に
 * なることがある。Claude の Messages API は**最初のメッセージが user ロールである
 * ことを要求する**ので、そのまま送ると上流が 400 を返してしまう。
 * そこで窓の先頭が user 発言になるまで先頭を捨てる（捨てるのは常に古い側だけなので、
 * 直近のやり取りは必ず残る）。
 *
 * 純粋関数（引数以外の状態を見ず、渡された配列も変更しない）にしてあるため、
 * 画面を起動しなくても単体テストで境界値を確認できる（§10 ロジックと UI の分離）。
 *
 * @param messages - 画面が保持している会話履歴（末尾が最新）。
 *          **末尾の user 発言（＝いま尋ねる質問）は呼び出し側が
 *          {@link findContentProblem} で検証済みであることを前提にする** —
 *          そこだけは黙って削らないので、未検証のまま渡すと上限を超えた本文が
 *          そのまま出力に残る（サーバーが理由付きの 400 を返す。次のターンでは
 *          過去の発言として切り詰められるので、その状態は 1 往復で解消する）
 * @returns 上の前提が満たされていれば、そのまま API へ送ってよい履歴
 *          （user 発言で**始まり**、user 発言で**終わり**、件数は
 *          {@link MAX_MESSAGE_COUNT} 以内、本文はいずれも
 *          {@link MAX_CONTENT_LENGTH} 以内）。
 *          送れる user 発言が 1 件も無い場合は空配列（送信側が呼ぶ限り、末尾は必ず
 *          今回のユーザー入力なので空にはならない）
 */
export function trimHistoryForRequest(
  messages: readonly Message[]
): Message[] {
  // 本文が空白だけのメッセージを先に取り除く。
  // サーバーは空白だけの本文を 400 で弾くため、これが履歴に紛れ込むと以降の送信が
  // すべて 400 になり、しかも往復が成立しないので 50 件の窓が進まず永久に抜けない
  // （件数・文字数の上限で塞いだのと同じ「復帰できない 400」を作らないための防御）
  const meaningful = messages.filter((message) => message.content.trim() !== "");

  // 直近 MAX_MESSAGE_COUNT 件だけを切り出す（古い側から捨てる）
  const recent = meaningful.slice(-MAX_MESSAGE_COUNT);

  // 窓の先頭が user 発言になる位置を探す（assistant で始まる窓は上流が 400 にするため）
  let start = 0;
  // 先頭が user 以外である間、開始位置を 1 つずつ後ろへずらす
  while (start < recent.length && recent[start].role !== "user") {
    start += 1;
  }

  // 窓の末尾が user 発言になる位置を探す。assistant 発言で終わる履歴は
  // サーバーが 400 で弾く（上流はその続きを書いてしまうため）。先頭と同じく、
  // 送れない形を組み立てないのはこのモジュールの役目なので、ここで整える。
  // 呼び出し側が末尾に今回のユーザー入力を積む限り 1 件も捨てられない
  let end = recent.length;
  // 末尾が user 以外である間、終了位置を 1 つずつ手前へ戻す
  while (end > start && recent[end - 1].role !== "user") {
    end -= 1;
  }

  // user 発言で始まり user 発言で終わる部分を取り出す
  const windowed = recent.slice(start, end);

  // 空になったら、履歴の中で最後の user 発言だけを送る。
  // 空配列を送るとサーバーが「メッセージを 1 件以上指定してください。」で 400 を
  // 返す ——「必ず 400 になるリクエストを送らない」ためのモジュールが、自ら
  // その状態を作ってしまう。呼び出し側が末尾に user 発言を積む限り起きないが、
  // 前提をコメントで書くだけにせず、実装側で成り立たせる
  if (windowed.length === 0) {
    // 末尾から最初に見つかる user 発言を探す。
    // Array#findLast は ES2023 で、このモジュールはブラウザへも配られる一方
    // tsconfig の target は ES2017（＝ TypeScript は補完コードを入れない）。
    // 古い実行環境では TypeError になり、しかも呼び出し元の catch が
    // 「通信エラー」として飲み込むため、実装の不具合が接続の問題に見える。
    // 後ろから探す単純なループなら、その前提を持ち込まずに済む
    let lastUserMessage: Message | undefined;
    for (let index = meaningful.length - 1; index >= 0; index -= 1) {
      // user 発言が見つかったらそれを採用して探索を終える
      if (meaningful[index].role === "user") {
        lastUserMessage = meaningful[index];
        break;
      }
    }
    // 見つからなければ送れるものが無いので空のまま返す（サーバーが弾く）。
    // 見つかった 1 件は必ず窓の外にある過去の発言（いま打った質問なら窓の末尾に
    // 残っているのでこの分岐には来ない）なので、本文は下と同じく上限に収める。
    // ここだけ収めそこねると、上限を超える発言を 1 件だけ送って必ず 400 になり、
    // この分岐が防ごうとしている「復帰できない 400」を自分で作ってしまう
    return lastUserMessage ? [capContent(lastUserMessage)] : [];
  }

  // 過去の発言の本文は受付上限に収めて返す。
  // 例外は末尾の user 発言（＝いま送ろうとしている質問）だけで、そこは削らない
  return windowed.map((message, index) =>
    isCurrentQuestion(message, index, windowed.length)
      ? message
      : capContent(message)
  );
}

/**
 * その発言が「いま送ろうとしている質問」かを判定する。
 * @param message - 判定する発言
 * @param index - 窓の中での位置
 * @param length - 窓の件数
 * @returns 末尾の user 発言なら true
 */
function isCurrentQuestion(
  message: Message,
  index: number,
  length: number
): boolean {
  // 窓の末尾にある user 発言だけが「これから尋ねる質問」に当たる
  return index === length - 1 && message.role === "user";
}

/**
 * 過去の発言の本文を受付上限の文字数に収める。
 *
 * <p>**assistant 発言は上流 Claude の回答なのでこちら側では長さを制御できない**。
 * max_tokens を広げているカテゴリ（料理・手続き）では上限を超える回答が返りうる。
 * それが履歴に入ると、サーバーの検証が「メッセージ本文が上限を超えています」で
 * 400 を返し、しかもその発言が 50 件の窓から抜けるには往復が必要なのに往復自体が
 * 全部 400 になるため、件数上限のときとまったく同じ「再読み込みするまで復帰
 * できない」状態になる。発言ごと捨てず切り詰めるのは、会話のターン構成
 * （誰がいつ何を言ったか）を保ったまま送れるようにするため。画面に表示する履歴は
 * 切り詰めないので、ユーザーから見える発言が欠けることはない。
 *
 * <p><b>いま尋ねようとしている質問（末尾の user 発言）だけは切り詰めない。</b>
 * ユーザーが打ったばかりの文章を黙って削ると、「質問が途中で切れたことに
 * 気づけないまま送信される」ことになる（入力欄に maxLength を付けないのと同じ理由。
 * §7 状態はテキストで伝える）。そちらは `findContentProblem` が送信前に理由付きで
 * 弾き、万一すり抜けてもサーバーが理由付きの 400 を返す。
 * <b>一方、過去の user 発言は切り詰める。</b> 履歴から読み直されるだけの文章は
 * もう編集できないので、削らずに送ると「必ず 400 になるのに窓からも抜けない」
 * 状態を作ってしまい、このモジュールが塞いだはずの穴がロール違いで再発する。
 *
 * @param message - 送信候補のメッセージ
 * @returns 本文が上限以内に収まったもの（元のオブジェクトは変更しない）
 */
function capContent(message: Message): Message {
  // 上限以内ならそのまま使う（無駄なオブジェクト生成もしない）
  if (message.content.length <= MAX_CONTENT_LENGTH) {
    return message;
  }

  // 末尾に付ける印の分だけ手前で切る（印を含めて上限に収める）。
  // 印を付けずに切ると、AI から見て「そこで終わった回答」と区別が付かない。
  // なお、画面側が付けた「途切れています」の印は本文の末尾にあるため、
  // ここで切り詰めると失われる。そのぶんを省略の印が引き継ぐので、
  // 「この回答は完全ではない」という情報自体は必ず残る
  // 0 を下回らないようにする。上限より印のほうが長い設定だと負の値になり、
  // slice(0, 負数) は「末尾から数えた位置まで」を返すため、切り詰めたつもりが
  // ほぼ全文を返して上限を超える（そのまま送ると復帰できない 400 になる）。
  // そもそもそんな設定にしないことは FieldLengths 的な不変条件としてテストで固定
  // しているが、計算そのものも反転しないようにしておく
  let end = Math.max(0, MAX_CONTENT_LENGTH - OMITTED_MESSAGE_SUFFIX.length);
  // 切り口がサロゲートペア（絵文字など 2 単位で 1 文字を表す並び）の途中なら 1 つ手前で切る。
  // 片割れだけ残すと文字として成立しない値を上流へ送ることになる
  if (isHighSurrogate(message.content.charCodeAt(end - 1))) {
    end -= 1;
  }

  // ロールはそのままに、切り詰めた本文＋省略の印を持つ新しいメッセージを返す
  return {
    role: message.role,
    content: `${message.content.slice(0, end)}${OMITTED_MESSAGE_SUFFIX}`,
  };
}

/**
 * 文字コードがサロゲートペアの前半（上位サロゲート）かを判定する。
 * @param code - 判定する UTF-16 の符号単位
 * @returns 上位サロゲートなら true
 */
function isHighSurrogate(code: number): boolean {
  // UTF-16 で上位サロゲートに割り当てられている範囲かを調べる
  return code >= 0xd800 && code <= 0xdbff;
}
